#!/usr/bin/env python3
"""Renders the terminal demo of the docs site from real apk-info output.

Runs `apk-info show --signatures --anomalies` on a sample with colors forced
on, turns the ANSI colors into `<span class="t-...">` and writes the HTML
snippet the quickstart includes. Its colors come from the site's stylesheet,
so the demo follows the light and dark theme.

    cargo build --release -p apk-info-cli
    python3 scripts/render-demo.py <sample.apk>

The sample is shown as `malware.apk`: it is copied to a temporary directory
under that name and never next to the repository.
"""

import argparse
import html
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "assets" / "demo.html"
COMMAND = ["show", "--signatures", "--anomalies", "malware.apk"]

# SGR codes of the `colored` crate to the classes of extra.css
CLASSES = {
    "1": "t-bold",
    "2": "t-dim",
    "31": "t-red",
    "32": "t-green",
    "33": "t-yellow",
    "34": "t-blue",
}

SGR = re.compile(r"\x1b\[([0-9;]*)m")


def to_html(text: str) -> str:
    """Escapes `text` and turns its SGR sequences into spans."""
    out, classes, pos = [], [], 0
    for match in SGR.finditer(text):
        out.append(html.escape(text[pos : match.start()]))
        pos = match.end()
        if classes:
            out.append("</span>")
        codes = [code for code in match[1].split(";") if code]
        classes = [] if codes in ([], ["0"]) else [CLASSES[code] for code in codes if code in CLASSES]
        if classes:
            out.append(f'<span class="{" ".join(classes)}">')
    out.append(html.escape(text[pos:]))
    if classes:
        out.append("</span>")
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("sample", type=Path, help="the APK to show")
    parser.add_argument(
        "--binary",
        type=Path,
        default=ROOT / "target" / "release" / "apk-info",
        help="the apk-info binary (default: target/release/apk-info)",
    )
    args = parser.parse_args()

    env = {key: value for key, value in os.environ.items() if key != "NO_COLOR"}
    env["CLICOLOR_FORCE"] = "1"

    with tempfile.TemporaryDirectory() as work:
        shutil.copyfile(args.sample, Path(work) / "malware.apk")
        output = subprocess.run(
            [args.binary.resolve(), *COMMAND],
            cwd=work,
            env=env,
            capture_output=True,
            text=True,
            check=True,
        ).stdout

    prompt = f'<span class="t-prompt">$</span> apk-info {" ".join(COMMAND)}'
    body = to_html(output.rstrip("\n"))
    OUTPUT.write_text(
        "<!-- generated by scripts/render-demo.py, do not edit -->\n"
        '<div class="apk-terminal" aria-label="apk-info output on a malware sample">\n'
        '<div class="apk-terminal__bar"><span></span><span></span><span></span></div>\n'
        f"<pre><code>{prompt}\n{body}</code></pre>\n"
        "</div>\n"
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
