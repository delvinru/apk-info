#!/usr/bin/env python3
"""Updates the Android framework resources of crates/axml.

Downloads public-final.xml, attrs_manifest.xml and attrs.xml from
frameworks/base/core/res/res/values in AOSP into crates/axml/src/assets, then
generates the Rust lookup tables from them:

- structs/system_types/table.rs: the names of system resources, by id;
- structs/attrs_manifest/table.rs: the enum and flag values of attributes.

By default the files come from the latest Android release tag; --ref takes a
tag (android-17.0.0_r1) or a branch instead. --offline only regenerates the
tables from the files already in assets.

usage: scripts/update-android-resources.py [--ref REF | --offline]
"""

import argparse
import base64
import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = "https://android.googlesource.com/platform/frameworks/base"
VALUES = "core/res/res/values"
CRATE = Path(__file__).resolve().parents[1] / "crates" / "axml" / "src"
ASSETS = CRATE / "assets"
SYSTEM_TYPES_TABLE = CRATE / "structs" / "system_types" / "table.rs"
ATTRS_TABLE = CRATE / "structs" / "attrs_manifest" / "table.rs"

FILES = ["public-final.xml", "attrs_manifest.xml", "attrs.xml"]

# resource types with names in the system table
SYSTEM_TYPES = [
    "attr", "id", "style", "string", "dimen", "color", "array", "drawable", "layout", "anim",
    "integer", "animator", "interpolator", "mipmap", "transition", "raw", "bool",
]

U32_MAX = 0xFFFF_FFFF


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def latest_release() -> str:
    """The newest `android-X.Y.Z_rN` tag of frameworks/base."""
    # gitiles prefixes its JSON with `)]}'` against XSSI
    tags = json.loads(fetch(f"{REPO}/+refs/tags?format=JSON").split(b"\n", 1)[1])
    releases = {}
    for tag in tags:
        if match := re.fullmatch(r"(?:refs/tags/)?(android-(\d+)\.(\d+)\.(\d+)_r(\d+))", tag):
            releases[match[1]] = tuple(int(part) for part in match.groups()[1:])
    if not releases:
        sys.exit("no android-X.Y.Z_rN tags found")
    return max(releases, key=releases.__getitem__)


def download(ref: str, name: str) -> bytes:
    # gitiles serves the raw file base64-encoded
    return base64.b64decode(fetch(f"{REPO}/+/{ref}/{VALUES}/{name}?format=TEXT"))


def system_types(public: Path) -> dict[int, str]:
    """`<public type= name= id=>` entries of the known types, by id.

    Entries without an id, like the staging groups of preview releases, are
    skipped.
    """
    by_type: dict[str, dict[int, str]] = {kind: {} for kind in SYSTEM_TYPES}
    for entry in ET.parse(public).getroot().iter("public"):
        kind, name, id_ = entry.get("type"), entry.get("name"), entry.get("id")
        if kind in by_type and name is not None and id_ is not None:
            by_type[kind][int(id_.removeprefix("0x"), 16)] = name

    table: dict[int, str] = {}
    for kind, entries in by_type.items():
        for id_, name in entries.items():
            if id_ in table:
                sys.exit(f"{id_:#010x} is both {table[id_]} and android:{kind}/{name}")
            table[id_] = f"android:{kind}/{name}"
    return table


def value(text: str) -> int:
    """An enum or flag value; a negative one, like -1, becomes `u32::MAX`."""
    if text.startswith("0x"):
        return int(text[2:], 16)
    if re.fullmatch(r"\+?\d+", text) and int(text) <= U32_MAX:
        return int(text)
    return U32_MAX


def attrs(path: Path) -> dict[str, tuple[str, dict[int, str]]]:
    """`<attr>` elements with `<enum>` or `<flag>` children: the kind, from the
    first child, and the names by value, the first name for a repeated value."""
    table: dict[str, tuple[str, dict[int, str]]] = {}
    for attr in ET.parse(path).getroot().iter("attr"):
        for item in attr:
            if item.tag not in ("enum", "flag"):
                continue
            _, items = table.setdefault(attr.get("name", ""), (item.tag, {}))
            items.setdefault(value(item.get("value", "")), item.get("name", ""))
    return table


def header(ref: str, sources: str) -> str:
    return (
        f"//! @generated by `scripts/update-android-resources.py` from {sources}\n"
        f"//! of frameworks/base `{ref}`. Do not edit.\n"
    )


def write_system_types(ref: str) -> None:
    table = system_types(ASSETS / "public-final.xml")
    if any(id_ >> 24 != 0x01 for id_ in table):
        sys.exit("a system resource id outside package 0x01")

    # 0x01TTEEEE is SYSTEM_TYPES[TT][EEEE]: ids are dense, so a lookup is two
    # indexings; an unused id is an empty name
    types: list[list[str]] = [[] for _ in range(max((id_ >> 16) & 0xFF for id_ in table) + 1)]
    for id_, name in sorted(table.items()):
        entries = types[(id_ >> 16) & 0xFF]
        entries.extend([""] * ((id_ & 0xFFFF) - len(entries)))
        entries.append(name)

    rows = []
    for type_, entries in enumerate(types):
        rows.append(f"    // 0x01{type_:02x}____\n    &[\n")
        rows.extend(
            f'        "{name}", // 0x01{type_:02x}{entry:04x}\n' for entry, name in enumerate(entries)
        )
        rows.append("    ],\n")

    SYSTEM_TYPES_TABLE.write_text(
        header(ref, "`public-final.xml`")
        + "\n/// Names of the framework's resources by type, then entry: `0x01TTEEEE` is\n"
        + "/// `SYSTEM_TYPES[TT][EEEE]`; an empty name is an unused id.\n"
        + "#[rustfmt::skip]\n"
        + "pub(super) static SYSTEM_TYPES: &[&[&str]] = &[\n"
        + "".join(rows)
        + "];\n"
    )


def write_attrs(ref: str) -> None:
    table = attrs(ASSETS / "attrs_manifest.xml")
    for name, entry in attrs(ASSETS / "attrs.xml").items():
        if name in table:
            sys.exit(f"{name} is declared in both attrs_manifest.xml and attrs.xml")
        table[name] = entry

    arms = []
    for name in sorted(table, key=str.encode):
        kind, items = table[name]
        # flags are matched from the highest value down
        values = ", ".join(
            f'("{item}", {item_value:#x})' if kind == "flag" else f'("{item}", {item_value})'
            for item_value, item in sorted(items.items(), reverse=True)
        )
        arms.append(f'        "{name}" => (Kind::{kind.capitalize()}, &[{values}]),\n')

    ATTRS_TABLE.write_text(
        header(ref, "`attrs_manifest.xml` and `attrs.xml`")
        + "\nuse super::{Kind, Values};\n"
        + "\n/// The kind and values of an attribute with enum or flag values; the values\n"
        + "/// are sorted from the highest down.\n"
        + "#[rustfmt::skip]\n"
        + "pub(super) fn attr(name: &str) -> Option<(Kind, Values)> {\n"
        + "    Some(match name {\n"
        + "".join(arms)
        + "        _ => return None,\n"
        + "    })\n"
        + "}\n"
    )


def current_ref() -> str:
    """The ref the tables were generated from, for --offline."""
    if match := re.search(r"frameworks/base `([^`]+)`", SYSTEM_TYPES_TABLE.read_text()):
        return match[1]
    return "unknown"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--ref", help="a tag or branch of frameworks/base, the latest release by default")
    group.add_argument("--offline", action="store_true", help="regenerate the tables from assets only")
    args = parser.parse_args()

    if args.offline:
        ref = current_ref()
    else:
        ref = args.ref or latest_release()
        print(f"frameworks/base at {ref}")
        for name in FILES:
            path = ASSETS / name
            data = download(ref, name)
            status = "unchanged" if path.exists() and path.read_bytes() == data else "updated"
            path.write_bytes(data)
            print(f"  {name}: {status}")

    write_system_types(ref)
    write_attrs(ref)
    print(f"tables: {SYSTEM_TYPES_TABLE.relative_to(CRATE)}, {ATTRS_TABLE.relative_to(CRATE)}")


if __name__ == "__main__":
    main()
